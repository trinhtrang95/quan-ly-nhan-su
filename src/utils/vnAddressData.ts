/**
 * Chuẩn hóa tên tỉnh để khớp với danh sách Tỉnh/Thành phố
 */
export function matchStandardProvince(raw: string): string {
  const cleaned = raw
    .trim()
    .replace(/^(tỉnh|thành phố|tp\.?)\s+/i, '')
    .trim();
  if (!cleaned) return '';

  const lower = cleaned.toLowerCase();
  if (raw.trim().toLowerCase() === 'tp. hồ chí minh') {
    return 'TP. Hồ Chí Minh';
  }

  // Kiểm tra trong ALL_PROVINCE_OPTIONS trước để giữ đúng tên tỉnh nếu người dùng chọn Hòa Bình, Bắc Giang...
  const exactInAll = ALL_PROVINCE_OPTIONS.find(
    (p) =>
      p.toLowerCase() === lower ||
      p.replace(/^TP\.\s*/i, '').toLowerCase() === lower
  );
  if (exactInAll) {
    return exactInAll;
  }

  if (MERGED_PROVINCE_ALIASES[lower]) {
    return MERGED_PROVINCE_ALIASES[lower];
  }

  const found = VN_34_PROVINCES.find(
    (p) =>
      p.toLowerCase() === lower ||
      p.replace(/^TP\.\s*/i, '').toLowerCase() === lower
  );
  return found || '';
}

/**
 * Ghép 3 phần địa chỉ thành chuỗi: [Địa chỉ chi tiết], [Xã/Phường], [Tỉnh/Thành phố]
 */
export function composeAddressFromParts(
  detail: string,
  commune: string,
  province: string
): string {
  const parts = [detail.trim(), commune.trim(), province.trim()].filter(
    (p) => p.length > 0 && p !== '-' && p !== '—'
  );
  return parts.join(', ');
}

/**
 * Tách chuỗi địa chỉ theo dấu phẩy để điền ngược lại vào 3 ô:
 * [Địa chỉ chi tiết], [Xã/Phường], [Tỉnh/Thành phố]
 * Bảo toàn 100% giá trị người dùng đã nhập (kể cả xã/phường hoặc tỉnh tự gõ).
 */
export function parseAddressIntoParts(
  fullAddress?: string | null
): ParsedAddressParts {
  if (!fullAddress) {
    return { detail: '', commune: '', province: '' };
  }
  const trimmed = fullAddress.trim();
  if (!trimmed || trimmed === '-' || trimmed === '—') {
    return { detail: '', commune: '', province: '' };
  }

  const segments = trimmed
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);

  if (segments.length === 0) {
    return { detail: '', commune: '', province: '' };
  }

  if (segments.length === 1) {
    const matchedProv = matchStandardProvince(segments[0]);
    if (matchedProv) {
      return { detail: '', commune: '', province: matchedProv };
    }
    return { detail: '', commune: segments[0], province: '' };
  }

  if (segments.length === 2) {
    const matchedProv = matchStandardProvince(segments[1]) || segments[1];
    const firstLower = segments[0].toLowerCase();
    const looksLikeDetailOnly =
      firstLower.startsWith('thôn ') ||
      firstLower.startsWith('xóm ') ||
      firstLower.startsWith('số ') ||
      firstLower.startsWith('ngõ ') ||
      firstLower.startsWith('đường ') ||
      firstLower.startsWith('tổ ');
    if (looksLikeDetailOnly) {
      return { detail: segments[0], commune: '', province: matchedProv };
    }
    return { detail: '', commune: segments[0], province: matchedProv };
  }

  // segments.length >= 3
  const lastSeg = segments[segments.length - 1];
  const matchedProv = matchStandardProvince(lastSeg) || lastSeg;
  const secondLast = segments[segments.length - 2];
  const thirdLast = segments[segments.length - 3];

  // Nếu địa chỉ cũ có dạng [Thôn/Chi tiết], [Xã/Phường], [Huyện/Quận], [Tỉnh]
  const secondLastLower = secondLast.toLowerCase();
  const thirdLastLower = thirdLast.toLowerCase();
  const isSecondLastDistrict =
    secondLastLower.startsWith('huyện ') ||
    secondLastLower.startsWith('quận ') ||
    secondLastLower.startsWith('thị xã ') ||
    secondLastLower.startsWith('tp ') ||
    secondLastLower.startsWith('thành phố ');
  const isThirdLastCommune =
    thirdLastLower.startsWith('xã ') ||
    thirdLastLower.startsWith('phường ') ||
    thirdLastLower.startsWith('thị trấn ');

  if (isSecondLastDistrict && isThirdLastCommune) {
    const detail = segments.slice(0, segments.length - 3).join(', ');
    return {
      detail,
      commune: thirdLast,
      province: matchedProv,
    };
  }

  const commune = secondLast;
  const detail = segments.slice(0, segments.length - 2).join(', ');

  return {
    detail,
    commune,
    province: matchedProv,
  };
}

/**
 * Định dạng địa chỉ rút gọn chuẩn 2 cấp [Xã/Phường], [Tỉnh/Thành phố]
 * (Ví dụ: "Xã Lương Sơn, Phú Thọ" hoặc "Phường Kinh Bắc, Bắc Ninh")
 * dùng cho cột ĐỊA CHỈ ngoài bảng danh sách nhân sự để luôn gọn trên 1 dòng.
 */
export function formatCommuneProvinceAddress(
  fullAddress?: string | null
): string {
  if (!fullAddress) return '';
  const trimmed = fullAddress.trim();
  if (!trimmed || trimmed === '-' || trimmed === '—') return '';

  const { commune, province, detail } = parseAddressIntoParts(trimmed);
  const cleanCommune = commune.trim();
  const cleanProvince = province.trim();

  if (cleanCommune && cleanProvince) {
    return `${cleanCommune}, ${cleanProvince}`;
  }
  if (cleanProvince) {
    return cleanProvince;
  }
  if (cleanCommune) {
    return cleanCommune;
  }
  return detail.trim() || trimmed;
}

/**
 * Nạp danh sách Xã/Phường/Thị trấn gợi ý theo Tỉnh/Thành phố
 */
export async function fetchCommunesForProvince(
  provinceName: string
): Promise<string[]> {
  const raw = (provinceName || '').trim();
  if (!raw) {
    return ALL_COMMUNES_SUGGESTIONS;
  }
  if (DEFAULT_COMMUNES_BY_PROVINCE[raw]) {
    return DEFAULT_COMMUNES_BY_PROVINCE[raw];
  }
  const matched = matchStandardProvince(raw);
  if (matched && DEFAULT_COMMUNES_BY_PROVINCE[matched]) {
    return DEFAULT_COMMUNES_BY_PROVINCE[matched];
  }
  const mergedTarget = MERGED_PROVINCE_ALIASES[raw.toLowerCase()];
  if (mergedTarget && DEFAULT_COMMUNES_BY_PROVINCE[mergedTarget]) {
    return DEFAULT_COMMUNES_BY_PROVINCE[mergedTarget];
  }
  return ALL_COMMUNES_SUGGESTIONS;
}
